"""Regenerate the checked-in caption font from pinned LVGL font sources.

Normal firmware builds use the generated C file and do not need Node.js.
"""

import argparse
import hashlib
import shutil
import subprocess
import tempfile
from pathlib import Path

FONT_SHA256 = "421f26b23e2be6b98373d32acd3cb2897b154d4bf0a77d26534ce476e4cbed53"
RANGES = (
    "0x20-0x7E,0xA0-0x17F,0x2007-0x200B,0x2010-0x2015,"
    "0x2018-0x201E,0x2020-0x2022,0x2026,0x2030,0x2032-0x2033,"
    "0x2039-0x203A,0x2044,0x20AC,0x2122,0x2190-0x2193,0x2212"
)
NOTICE = """/* SPDX-License-Identifier: OFL-1.1
 * Copyright 2011 The Montserrat Project Authors
 * (https://github.com/JulietaUla/Montserrat).
 * Bitmap subset generated by tools/generate_caption_font.py; see README.md
 * and LICENSE.OFL in this directory. Do not edit the generated tables.
 */
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lvgl-dir", required=True, type=Path)
    parser.add_argument("--converter", default="lv_font_conv")
    args = parser.parse_args()
    source = args.lvgl_dir / "scripts/built_in_font/Montserrat-Medium.ttf"
    if hashlib.sha256(source.read_bytes()).hexdigest() != FONT_SHA256:
        parser.error("Montserrat source does not match the pinned SHA-256")
    converter = shutil.which(args.converter)
    if not converter:
        parser.error("Install lv_font_conv@1.5.3 and pass its executable path")
    version = subprocess.check_output([converter, "--version"], text=True).strip()
    if version != "1.5.3":
        parser.error("Use lv_font_conv@1.5.3 for reproducible output")
    destination = (
        Path(__file__).resolve().parents[1]
        / "examples/waveshare/fonts/live_caption_font_22.c"
    )
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        shutil.copyfile(source, root / "Montserrat-Medium.ttf")
        subprocess.run(
            [
                converter,
                "--no-compress",
                "--no-prefilter",
                "--bpp",
                "4",
                "--size",
                "22",
                "--font",
                "Montserrat-Medium.ttf",
                "-r",
                RANGES,
                # Identical ink, different Unicode line-breaking semantics.
                "-r",
                "0x2010=>0x2011",
                "-r",
                "0x2009=>0x202F",
                "--format",
                "lvgl",
                "--lv-font-name",
                "live_caption_font_22",
                "-o",
                destination.name,
            ],
            cwd=root,
            check=True,
        )
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(
            NOTICE + (root / destination.name).read_text().rstrip() + "\n"
        )
    print(destination)


if __name__ == "__main__":
    main()
